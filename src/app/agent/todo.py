"""任务清单：agent 自己维护的那张进度表。

**装的是上游的 `TodoListMiddleware`，换掉的是它那两段英文。** 上游原文
5243 字符（注入提示词 1370 + 工具描述 3873），是平台自己整份系统提示词的八倍，
而且**全英文会诱导模型写英文条目** —— 那张清单是给教师看的，
项目的规矩是面向用户的文字一律中文，因此这里点明「条目用中文写」。

**缓存上是安全的**：中间件追加的是静态 prose，前缀仍逐字节稳定，
不打破「每轮请求是上一轮的严格扩展」那条规则。代价只在第一轮多付一次未命中。

**只装主图。** 与 `INTERRUPT_ON`「主图子图必须同一份」那条规矩相反是有意的：
那条管的是安全闸，漏一处就漏一条绕过路径；清单是展示，多一张只会与主清单
互相覆盖，前端还要回答「哪张是当前的」。
"""

from langchain.agents.middleware.todo import TodoListMiddleware

TODO_TOOL = "write_todos"

# 中间件把清单写在 state 的这个键上。**名字由上游定**，平台只是读它 ——
# 尾部注入的进度节与事件映射都认这个键，它改名的话两处一起静默失灵
TODO_STATE_KEY = "todos"

TODO_SYSTEM_PROMPT = """## 任务清单（`write_todos`）

多步分析开始前，先用 `write_todos` 把要做的步骤列出来，做的过程中随时更新它。
教师在界面上看得见这张清单，它是他判断「现在做到哪儿了」的唯一依据。

- 三步以内能做完的问题不要用它，写清单本身也要花时间和 token
- 动手做一步之前先把那一步标成 `in_progress`，做完立刻标 `completed`，不要攒着一起标
- 除非全部做完，任何时候都该有一条 `in_progress`
- 一次模型回复里只调它一次，不要并行调用
- 条目一律用中文写

## 收尾

最后一次 `write_todos` 之后要再说一段话，把教师问的东西答出来 ——
清单只是进度，把最后一条标成完成不等于回答了问题。"""

TODO_TOOL_DESCRIPTION = """建立并更新本次分析的任务清单。教师在界面上直接看得见它。

## 什么时候用

- 要三步以上才能做完的分析（读数据 → 清洗 → 计算 → 出图 → 写结论 这类）
- 教师一口气提了好几件事
- 先做几步才能知道后面怎么走，计划中途要改的

## 什么时候不要用

- 一两步就能答完的问题，或者纯属聊天、只是问一句概念
- 已经清楚该怎么做且只剩一次工具调用的收尾动作

## 怎么用

1. 开工前列出全部步骤，并把第一条标成 `in_progress`；
2. 每做完一条立刻标 `completed`，同时把下一条标成 `in_progress`；
3. 中途发现新步骤就加进去，发现某步没必要了就删掉，已完成的不要改；
4. 一次可以改多条，但**一次模型回复里只调一次这个工具**；
5. 出错、卡住、做了一半时**保持 `in_progress`**，另加一条写清楚卡在哪 ——
   标成完成而实际没做完，教师看到的进度就是假的。

## 三种状态

- `pending`：还没开始
- `in_progress`：正在做（互不相关、能并行的可以同时有几条）
- `completed`：真的做完了

## 两条硬规矩

- **条目用中文写**，写成教师看得懂的一句话，例如「计算各行业年化波动率」，
  不要写成函数名或英文缩写；
- 清单不是答复。教师要的结论、数字、图表，必须写在最后一次调用之后的那段话里。"""


def create_todo_middleware() -> TodoListMiddleware:
    """造一份装了中文提示词的任务清单中间件。

    **每次装配现造一个**，不做成模块级单例 —— 中间件持有工具对象并会被绑进图，
    共享一个可变对象是平台明令禁止的那类全局状态。

    Returns:
        可直接放进主图 `middleware` 列表的中间件。
    """
    return TodoListMiddleware(system_prompt=TODO_SYSTEM_PROMPT, tool_description=TODO_TOOL_DESCRIPTION)
